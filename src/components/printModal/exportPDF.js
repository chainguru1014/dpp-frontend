import React from 'react';
import { Document, Page, View, StyleSheet, Image, Text } from '@react-pdf/renderer';

// Create styles
const styles = StyleSheet.create({
  page: {
    backgroundColor: '#fff',
    padding: '80px 40px 50px 40px',
    fontSize: '10px',
    fontWeight: 'thin',
    display: 'flex',
  },
});

const splitIdentifier = (item) => {
  const text = `${item.type} : ${item.serial}`;
  const parts = [];
  for (let i = 0; i < Math.round(text.length / 15); i++) {
    parts.push(text.substr(i * 15, 15));
  }
  return parts;
};

// A4 page is 595pt wide; styles.page pads 40pt each side, leaving ~515pt of
// content width to divide across however many items go in one row.
const PAGE_CONTENT_WIDTH = 515;
const ITEM_MARGIN = 6;

/**
 * Props-driven PDF document. The QR images are pre-generated by the caller and
 * passed in (`items: [{ img, identifiers }]`), so the document never renders an
 * empty <Image> — which previously produced a blank PDF when the async QR image
 * generation hadn't completed before react-pdf built the blob. `itemsPerRow`
 * controls how many items fit across one line (see PrintModal's "Items per
 * row" field) — the previous fixed 100px box only ever fit however many
 * happened to flex-wrap onto a line.
 */
const MyDocument = ({ items = [], itemsPerRow = 5 }) => {
  const perRow = Math.max(1, Number(itemsPerRow) || 5);
  const itemSize = Math.max(30, Math.floor(PAGE_CONTENT_WIDTH / perRow) - ITEM_MARGIN * 2);

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={{ display: 'flex', flexDirection: 'row', flexWrap: 'wrap' }}>
          {items.map((it, index) => (
            <View key={index} style={{ width: `${itemSize}px`, margin: `${ITEM_MARGIN}px` }}>
              {!!it.img && <Image src={it.img} style={{ width: `${itemSize}px`, height: `${itemSize}px` }} />}
              <View>
                {(it.identifiers || []).map((item, j) => (
                  <View key={j}>
                    {splitIdentifier(item).map((info, k) => (
                      <Text key={k} style={{ fontSize: 12, color: 'black' }}>{info}</Text>
                    ))}
                  </View>
                ))}
              </View>
            </View>
          ))}
        </View>
      </Page>
    </Document>
  );
};

export default MyDocument;
